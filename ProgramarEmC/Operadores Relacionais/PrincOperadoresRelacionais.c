#include <stdio.h>

int main(){
    int a = 10;
    int b = 20;

    printf("a > b: %d\n", a > b); // 0
    printf("a < b: %d\n", a < b); // 1
    printf("a == b: %d\n", a == b); // 0
    printf("a != b: %d\n", a != b); // 1

    // 0 = falso, ou seja representa o não.
    // 1 = verdadeiro, ou seja representa o sim.

    return 0;
    
}